def node(key, row, lane, kind, label):
    return {"id": key, "row": row, "lane": lane, "kind": kind, "label": label}


def edge(source, target, label="", side=None):
    return {"source": source, "target": target, "label": label, "side": side}


def sheet(key, title, nodes, edges, note=""):
    return {"id": key, "title": title, "nodes": nodes, "edges": edges, "note": note}


def flow(key, title, sheets, connectors=()):
    return {"id": key, "title": title, "sheets": sheets, "connectors": list(connectors)}


